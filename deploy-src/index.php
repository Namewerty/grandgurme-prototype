/* МАРШРУТИЗАТОР. Веб-сервер стенда отдаёт корневой index.php на любой
   ненайденный путь, и до правил обработки адресов Битрикса дело не доходит:
   правило #^/catalog/# в админке заведено, но не срабатывает — /product/zzz
   отвечает 200 и содержимым главной. Разбор берём на себя: две проверки
   здесь дешевле переписывания конфига сервера, к которому доступа нет.
   Если правила когда-нибудь заработают, эти строки просто перестанут
   вызываться — свои файлы у /catalog/ и /product/ есть. */
$ggPath = (string)parse_url($_SERVER['REQUEST_URI'] ?? '/', PHP_URL_PATH);
if (preg_match('#^/catalog(/|$)#', $ggPath)) {
    require __DIR__ . '/catalog/index.php';
    return;
}
if (preg_match('#^/product(/|$)#', $ggPath)) {
    require __DIR__ . '/product/index.php';
    return;
}

