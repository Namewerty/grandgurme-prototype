/* ============================================================================
   Состав шапки альтернативной версии. ЧЕРНОВИК НА ВЫБРОС.

   ЗДЕСЬ ТОЛЬКО КАРТЫ И ПОРЯДОК. Ни одной ссылки, ни одного названия
   категории, ни одного адреса: значения импортируются из src/data/*.
   Дублировать их нельзя — через одну правку основной версии альтернатива
   разошлась бы с каталогом и с панелью «Компания», и разошлась бы молча.

   Что меняется против основной шапки:

   1. Пункт «Икра» убран. Чёрная икра остаётся в один клик: она первая
      в каталожной панели и открыта в ней по умолчанию, плюс стоит
      в быстрых ссылках нижней строки панели. Отдельный пункт её дублировал.

   2. Панель «Компания» разобрана на три пункта первого уровня:
      Покупателям · Компания · Партнёрам. Это ровно три колонки, которые
      уже лежат в companyPanel.columns; третья переименована в «Партнёрам»
      (в данных она «Сотрудничество» — слово о процессе, а не об адресате).

   3. Иконка «Избранное» убрана. На момент сборки черновика она вела во
      вкладку личного кабинета — туда же, куда соседняя иконка человечка:
      дублирующий таб-стоп в самом плотном месте шапки. С 17.09.2026
      у избранного свой адрес /favorites; если черновик пойдёт в работу,
      решение стоит пересмотреть.

   4. Категории каталожной панели разложены по двум подстолбцам. Десять
      категорий одной колонкой держали высоту панели; пополам они делятся
      по смыслу без натяжки.
   ============================================================================ */

import { categories } from '../data/catalog.js'
import { companyPanel } from '../data/company.js'
import { navActions, navPrimary } from '../data/nav.js'

/* ---------------------------------------------- левая группа шапки */

/** Товарные пункты без «Икры» — см. п. 1 в шапке файла. */
export const altNavPrimary = navPrimary.filter((item) => item.panel !== 'caviar')

/* ---------------------------------------------- иконочная группа */

/** Без «Избранного» — см. п. 3. Ключ, а не подпись: подпись заказчик правит. */
export const altNavActions = navActions.filter((item) => item.key !== 'heart')

/* ---------------------------------------------- правая группа шапки */

/**
 * Три информационных пункта. Порядок и подписи задаются здесь, содержимое
 * берётся из колонки с тем же title в src/data/company.js.
 *
 * title  — по какой колонке искать. Совпадает со значением в данных;
 *          это ключ поиска, а не текст на экране.
 * label  — что стоит в шапке. Отличается от title только у «Партнёрам».
 * panel  — ключ сборщика в src/alt/panels.js. У всех трёх — свой, потому
 *          что ключ company занят исходной трёхколоночной панелью: она
 *          возвращается на ширинах 1024–1359 (см. src/alt/header.js).
 */
const INFO_ITEMS = [
  { title: 'Покупателям', label: 'Покупателям', panel: 'buyersMini' },
  { title: 'Компания', label: 'Компания', panel: 'companyMini' },
  { title: 'Сотрудничество', label: 'Партнёрам', panel: 'partnersMini' },
]

const columnByTitle = (title) => companyPanel.columns.find((column) => column.title === title)

/**
 * Пункты правой группы в широком режиме. Колонка, которой в данных не
 * нашлось, пункта не даёт вовсе: пустая панель хуже отсутствующего пункта,
 * а шеврон над ней был бы прямым обманом.
 *
 * href — первая ссылка колонки. Настоящий адрес нужен и без JS, и на
 * мобильном, и клавиатуре: пункт обязан куда-то приводить.
 */
export const infoItems = INFO_ITEMS.map((item) => {
  const column = columnByTitle(item.title)
  if (!column || !column.links.length) return null
  /* Кадр бутика показывает только «Компания»: панель без единой картинки
     на всю шапку выглядит служебным меню, и один кадр это чинит — ровно
     та же мотивировка, что в основной версии. Вешать кадр на все три
     значило бы утроить его и утроить высоту. */
  const feature = item.title === 'Компания' ? companyPanel.feature : null
  return { ...item, href: column.links[0].href, links: column.links, feature }
}).filter(Boolean)

/* ---------------------------------------------- каталожная панель */

/**
 * Группировка категорий по подстолбцам. Только слаги: названия берутся
 * из src/data/catalog.js по слагу.
 *
 * Категорий десять, и делятся они пополам без натяжки: слева то, за чем
 * приходят в гастробутик, справа то, что берут к этому и для дома.
 * Порядок внутри групп — исходный порядок каталога, он значим.
 */
export const categoryGroups = [
  {
    title: 'Деликатесы',
    slugs: [
      'chernaya-ikra',
      'krasnaya-ikra',
      'ryba',
      'kraby-i-moreprodukty',
      'podarochnye-nabory',
    ],
  },
  {
    title: 'Гастрономия и дом',
    slugs: ['bakaleya', 'sladosti', 'sneki', 'napitki', 'tovary-dlya-doma'],
  },
]

/**
 * Категории по подстолбцам, в порядке карты выше. Категория, которой
 * в карте нет, уходит в последний подстолбец — иначе новый раздел каталога
 * молча пропал бы из панели, и заметили бы это на показе.
 */
export function groupedCategories() {
  const mapped = new Set(categoryGroups.flatMap((group) => group.slugs))
  const rest = categories.filter((category) => !mapped.has(category.slug))

  return categoryGroups.map((group, index) => ({
    title: group.title,
    items: [
      ...group.slugs
        .map((slug) => categories.find((category) => category.slug === slug))
        .filter(Boolean),
      ...(index === categoryGroups.length - 1 ? rest : []),
    ],
  }))
}
