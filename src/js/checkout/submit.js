/* ============================================================================
   Отправка заказа. ОДНА функция, и на Битриксе она заменяется целиком.

   В прототипе заказ никуда не уходит: он кладётся в хранилище браузера,
   получает номер, корзина очищается, и страница уводит на
   /order-success?n=<номер>. На Битриксе здесь будет запрос к sale.order:
   номер присвоит сервер, корзину очистит он же, а форма, проверка полей
   и страница успеха останутся как есть.

   Номер берётся из адреса страницы успеха, а не из памяти: так страницу
   можно перезагрузить или открыть из письма.
   ============================================================================ */

import { ROUTES } from '../../data/routes.js'
import { loadOrder, saveOrder } from '../cart/storage.js'
import { clear } from '../cart/store.js'

/**
 * @param {object} payload контакты, способ получения, дата и интервал, оплата,
 *   комментарий, промокод, состав и итоги — см. collectPayload в checkout-page.js
 * @returns {Promise<number>} номер заказа (до ухода со страницы)
 */
export async function submitOrder(payload) {
  const number = saveOrder({ ...payload, createdAt: new Date().toISOString() })
  clear()
  location.assign(`${ROUTES.orderSuccess}?n=${number}`)
  return number
}

/**
 * Заказ для страницы «Заказ принят». На Битриксе — запрос к серверу
 * по номеру и пользователю. null — заказ из другого браузера или номер
 * набран руками: страница тогда показывает шаги без состава.
 */
export function getOrder(number) {
  return loadOrder(number)
}
