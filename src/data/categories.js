/**
 * «Не только икра» (#categories) — навигация по ассортименту.
 *
 * История блока в двух шагах. Сначала здесь стояли три большие фотоплитки 3:4:
 * из десятка разделов показывались ровно три, крупные кадры дублировали
 * витрину рядом, и служебный по смыслу блок занимал экран целиком. Их сменила
 * узкая лента на двенадцать плиток со знаками — компактно, но заказчик
 * справедливо сказал, что мелкие плитки в слайдере выглядят дёшево и листать
 * их никто не станет.
 *
 * Сейчас: ВОСЕМЬ разделов решёткой 4×2 на одном экране, без прокрутки.
 * Ничего листать не нужно — весь блок виден сразу. Освободившееся место
 * ушло в воздух внутри ячейки: знак стал крупнее, название набрано
 * заголовочной антиквой, счётчик получил слово «позиции» вместо голой цифры.
 *
 * ВОСЕМЬ ЯЧЕЕК = ВЕСЬ КАТАЛОГ, КРОМЕ ИКРЫ. Это не выборка «главного» и не
 * компромисс ради решётки: после перекомпоновки дерева (src/data/catalog.js)
 * неикорных разделов верхнего уровня ровно восемь, и каждый стоит здесь
 * ровно один раз. Ничего не выпало и ничего не выбрано произвольно —
 * ради этого мелкие разделы 1С и были укрупнены. Секция называется
 * «Не только икра», поэтому чёрная и красная икра сюда не входят: обе
 * доступны из шапки, из каталожной панели и из подвала.
 *
 * Девятая ячейка оставит в ряду три пустых места — если раздел добавят,
 * придётся возвращать третий ряд.
 *
 * СЧЁТЧИКИ НАСТОЯЩИЕ. Числа — из выгрузки 1С от 20.08.2026 (Приложение А),
 * с учётом склейки разделов: «Снеки и орехи» = 31 + 5 + 2, «Напитки» =
 * 42 + 22. Обновлять их вместе с выгрузкой.
 *
 * icon — ключ из src/js/icons.js (набор cat*).
 * href — страницы разделов из src/data/routes.js. Состав решётки и состав
 * каталожной панели в шапке ведутся отдельно и намеренно, но названия
 * разделов должны совпадать: правите список в src/data/catalog.js —
 * поправьте и здесь.
 */

