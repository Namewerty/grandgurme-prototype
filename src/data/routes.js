/** Страница по адресу. Нужна заглушкам: они узнают себя по location. */
export function findPage(path) {
  const clean = path.replace(/\/index\.html$/, '').replace(/(.)\/$/, '$1')
  return allPages.find((page) => page.path === clean) || null
}
