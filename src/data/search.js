/** Плоский список товаров, по которому ищем. */
const PRODUCTS = [
  ...caviarProducts.map((product) => ({ product, categorySlug: 'chernaya-ikra' })),
  ...fishProducts.map((product) => ({ product, categorySlug: 'ryba' })),
]

const normalize = (text) =>
  String(text).toLowerCase().replace(/ё/g, 'е').replace(/\s+/g, ' ').trim()

/** Позиция по слагу — нужна блоку «недавно смотрели». */
export const productBySlug = (slug) =>
  PRODUCTS.find((entry) => entry.product.slug === slug) || null

/**
 * Поиск по набору. Возвращает товары и разделы; ограничение — чтобы панель
 * не превращалась в страницу выдачи, за полным списком есть «Показать все».
 *
 * @param {string} query
 * @param {{products?: number, categories?: number}} [limits]
 */
export function searchAll(query, limits = {}) {
  const { products: productLimit = 5, categories: categoryLimit = 4 } = limits
  const q = normalize(query)

  if (q.length < 2) return { query, products: [], categories: [], total: 0 }

  const found = PRODUCTS.filter(({ product }) => {
    const haystack = normalize(
      [product.name, product.weightLabel, product.attrs?.grade, product.attrs?.brand]
        .filter(Boolean)
        .join(' '),
    )
    return haystack.includes(q)
  })

  const foundCategories = categories.filter((category) => {
    const haystack = normalize(
      [category.name, ...(CATEGORY_SYNONYMS[category.slug] || [])].join(' '),
    )
    return haystack.includes(q)
  })

  return {
    query,
    products: found.slice(0, productLimit),
    categories: foundCategories.slice(0, categoryLimit),
    total: found.length + foundCategories.length,
  }
}

