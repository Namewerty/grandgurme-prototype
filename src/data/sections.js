/**
 * Реестр секций главной. Один источник правды: из него собираются оболочки,
 * чередование фонов и номера в кольце прогресса.
 *
 * dark  — секция тёмная (.section--dark переопределяет токены внутри себя)
 * full  — min-height 100svh. Остался ТОЛЬКО у hero: заказчик просил компактную
 *         страницу, остальные секции ровно такой высоты, какой требует контент
 * tight — секция продолжает главу предыдущей: верхний отступ уменьшен, пара
 *         читается одним разворотом. Носитель один — #season после #shop
 * ring  — название остановки в кольце прогресса
 *
 * ПРО ПОРЯДОК. Порядок правился трижды, последний раз — по правке заказчика
 * «икра должна идти раньше рассказа о себе».
 *
 * 1. #types ↔ #categories. Виды икры идут ПЕРЕД ассортиментом. Икра — то,
 *    ради чего сюда пришли, и страница обязана показать её, а не оглавление
 *    каталога. «Не только икра» после четырёх видов читается ровно так, как
 *    написано в заголовке: сначала главное, потом «а ещё есть вот это».
 *
 * 2. #shop ↔ #proof. Полоса доверия (рестораны, отели, документы) идёт ПЕРЕД
 *    витриной. Цены показывают после того, как ответили «почему вам можно
 *    верить», а не до: 6 900 ₽ за банку краба без этого ответа выглядит просто
 *    дорого. Заодно тёмная секция встала ровно в середину светлой полосы
 *    и держит ритм страницы там, где раньше шли шесть светлых подряд.
 *
 * 3. #brand уехал ВНИЗ, за #categories. Заказчик просил показать икру раньше
 *    рассказа о бренде, и это правильно: человек пришёл за икрой. Но буквальная
 *    перестановка соседей дала бы types → brand → categories и разорвала пару,
 *    которая держится на тексте: заголовок #categories — «Не только икра», и он
 *    читается только сразу после блока с икрой. Поэтому вниз уехал #brand,
 *    а не вверх #types: требование выполнено, пара цела, а рассказ о бренде
 *    встал вплотную к тёмному #proof — «кто мы» переходит прямо в «нам
 *    доверяют», связка сильнее прежней.
 *    Если заказчик захочет именно буквальный вариант (types → brand →
 *    categories) — это перестановка двух строк в массиве ниже.
 *
 * Ритм фонов: тёмная → светлая ×4 → ТЁМНАЯ → светлая ×5 → тёмный подвал.
 * Тёмный разворот посередине делит страницу на «кто мы и что у нас есть»
 * и «как купить». Светлых в хвосте пять, а не четыре, потому что #season —
 * не самостоятельная глава, а продолжение витрины (флаг tight, своей
 * остановки в кольце нет).
 *
 * Про ring. Остановок девять, а секций десять: #trust — узкая полоса доверия
 * сразу под первым экраном, самостоятельной остановкой она не читается и
 * относится к «01 Начало». Секция без ring наследует номер и название
 * предыдущей (склейка — в js/sections/index.js).
 *
 * Тексты наполненных секций живут в своих data-файлах, а разметку собирает
 * модуль из src/js/sections/ — здесь только структурные флаги и место
 * в порядке.
 *
 * ПРО ХВОСТ. На месте #delivery («Доедет холодным») стоит #why: блок отвечал
 * на вопрос «как доедет», а страница в этом месте должна отвечать на «почему
 * здесь, а не где угодно ещё». Позиция в порядке та же, сменились id и
 * название — см. why.js.
 *
 * Остановка #why переименована с «Почему мы» на «Стандарт» вслед за
 * заголовком блока: премиальный бренд не объясняет, почему у него покупают,
 * а заявляет, за что отвечает. Сам id секции не трогаем — он завязан
 * на сборщик, стили и реестр.
 */

