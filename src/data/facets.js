/**
 * Схема фасет: какой набор фильтров показывает страница каждой категории.
 *
 * Развязка конфликта «универсальность фасет». Вёрстка страницы категории одна
 * на все разделы, а состав фильтров задаётся здесь. У фасеты есть роль, и
 * ролей ровно три — больше вёрстка не знает:
 *
 *   chips  строка капсул, множественный выбор, первая капсула «Все».
 *          Главная ось раздела — у обеих рабочих категорий это ВИД:
 *          у рыбы вид рыбы, у икры вид икры.
 *   tabs   строка табов с подчёркиванием, одиночный выбор, первый таб «Всё».
 *          Вторая ось: у рыбы обработка, у икры фасовка.
 *   pill   пилюля с шевроном и поповером. Всё остальное.
 *
 * ОПЦИИ НЕ ПЕРЕЧИСЛЯЮТСЯ РУКАМИ. Список значений собирается из товаров
 * (collectOptions в src/js/catalog/model.js): список опций и данные разъехаться
 * не могут в принципе. Поле order задаёт порядок там, где алфавит бессмыслен
 * (обработка, фасовка); всё, чего нет в order, уезжает в конец по алфавиту.
 *
 * ФАСЕТА ЕСТЬ ТОЛЬКО ТАМ, ГДЕ ЕСТЬ ДАННЫЕ. После выгрузки из 1С это перестало
 * быть теорией: у чёрной икры нет ни цен, ни стран, ни брендов, ни дат
 * поступления, и соответствующих фасет и сортировок у раздела просто нет.
 * Пустая пилюля «Цена» с нулевым диапазоном читается как поломка сайта,
 * а не как отсутствие данных, — поэтому её нет вовсе.
 */

