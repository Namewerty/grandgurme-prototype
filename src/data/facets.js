export const DEFAULT_SORT = 'popular'

/** Сортировки раздела: schema.sorts — белый список ключей, порядок общий. */
export const sortsFor = (schema) =>
  schema?.sorts ? SORT_OPTIONS.filter((option) => schema.sorts.includes(option.key)) : SORT_OPTIONS

/** Сортировка по умолчанию для раздела: первая из доступных ему. */
export const defaultSortFor = (schema) => {
  const list = sortsFor(schema)
  return list.some((option) => option.key === DEFAULT_SORT) ? DEFAULT_SORT : list[0].key
}

